const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('api', {
  q: (name, ...args) => ipcRenderer.invoke('q', name, ...args),
  refocus: () => ipcRenderer.invoke('win:refocus'),
  logError: (msg, stack) => ipcRenderer.invoke('log:renderer', msg, stack),
  openLogs: () => ipcRenderer.invoke('log:open'),
  info: () => ipcRenderer.invoke('app:info'),
  pickAndImport: () => ipcRenderer.invoke('import:pick'),
  pickAndEnrich: () => ipcRenderer.invoke('enrich:pick'),
  importFiles: files => ipcRenderer.invoke('import:files', files.map(f => webUtils.getPathForFile(f))),
  task: (name, args) => ipcRenderer.invoke('task', name, args),
  exportErrors: (f, sort) => ipcRenderer.invoke('export:errors', f, sort),
  exportAnalysis: (title, rows) => ipcRenderer.invoke('export:analysis', title, rows),
  exportInventory: (asOf, by, level, acc, bp) => ipcRenderer.invoke('export:inventory', asOf, by, level, acc, bp),
  exportAging: (asOf, term, level, grp, acc, dim) => ipcRenderer.invoke('export:aging', asOf, term, level, grp, acc, dim),
  exportReport: (minSev, group) => ipcRenderer.invoke('export:report', minSev, group),
  exportEmployee: (u, minSev, group) => ipcRenderer.invoke('export:employee', u, minSev, group),
  mailPreview: (u, o) => ipcRenderer.invoke('mail:preview', u, o),
  sendMails: (list, o) => ipcRenderer.invoke('mail:send', list, o),
  getSmtp: () => ipcRenderer.invoke('smtp:get'),
  setSmtp: cfg => ipcRenderer.invoke('smtp:set', cfg),
  verifySmtp: () => ipcRenderer.invoke('smtp:verify'),
  emailOf: u => ipcRenderer.invoke('util:emailOf', u),
  backupNow: () => ipcRenderer.invoke('backup:now'),
  listBackups: () => ipcRenderer.invoke('backup:list'),
  restoreBackup: f => ipcRenderer.invoke('backup:restore', f),
  pickBackup: () => ipcRenderer.invoke('backup:pick'),
  openingTemplate: () => ipcRenderer.invoke('opening:template'),
  importOpening: () => ipcRenderer.invoke('opening:pick'),
  riskPdf: () => ipcRenderer.invoke('report:pdf'),
  kqTemplate: () => ipcRenderer.invoke('kq:template'),
  dmImport: (kind, mode) => ipcRenderer.invoke('dm:import', kind, mode),
  xlsColor: (name, sheet, aoa, opt) => ipcRenderer.invoke('xls:color', name, sheet, aoa, opt),
  faAssetRead: () => ipcRenderer.invoke('fa:assetRead'),
  advReconPdf: (key, o) => ipcRenderer.invoke('adv:reconPdf', key, o),
  setLang: l => ipcRenderer.invoke('ui:lang', l),
  gsExport: R => ipcRenderer.invoke('gs:export', R),
  khExport: (P1, P6, o) => ipcRenderer.invoke('kh:export', P1, P6, o),
  khImport: () => ipcRenderer.invoke('kh:import'),
  oiExport: (R, o) => ipcRenderer.invoke('oi:export', R, o),
  oiImport06: () => ipcRenderer.invoke('oi:import06'),
  apExport: (bps, o, kinds) => ipcRenderer.invoke('ap:export', bps, o, kinds),
  invImport: mode => ipcRenderer.invoke('inv:import', mode),
  llImport: () => ipcRenderer.invoke('ll:import'),
  advReconBook: (keys, o) => ipcRenderer.invoke('adv:reconBook', keys, o),
  advReconMail: (keys, o) => ipcRenderer.invoke('adv:reconMail', keys, o),
  staffImport: mode => ipcRenderer.invoke('staff:import', mode),
  staffMail: (list, subject, body) => ipcRenderer.invoke('staff:mail', list, subject, body),
  catImport: mode => ipcRenderer.invoke('cat:import', mode),
  xlsxSheets: (name, sheets) => ipcRenderer.invoke('xlsx:sheets', name, sheets),
  recvXlsx: (acc, asOf, term) => ipcRenderer.invoke('report:recv', acc, asOf, term),
  finXlsx: p => ipcRenderer.invoke('report:fin', p),
  accrueErp: (items, o) => ipcRenderer.invoke('report:accrueErp', items, o),
  reversalErp: (keys, o) => ipcRenderer.invoke('report:reversalErp', keys, o),
  accrualXlsx: (f, t, a) => ipcRenderer.invoke('report:accrual', f, t, a),
  openDbFolder: () => ipcRenderer.invoke('db:openFolder'),
  onProgress: fn => ipcRenderer.on('progress', (_e, m) => fn(m)),
  onReload: fn => ipcRenderer.on('reload', () => fn()),
});
